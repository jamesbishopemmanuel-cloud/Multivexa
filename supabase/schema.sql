-- Flutterwave wallet: only the trusted server can credit balances.
create table if not exists public.wallet_balances (
  user_id uuid primary key references auth.users(id) on delete cascade,
  credits integer not null default 0 check (credits >= 0),
  updated_at timestamptz not null default now()
);
alter table public.wallet_balances enable row level security;
grant select on public.wallet_balances to authenticated;
drop policy if exists "Users can read their own wallet" on public.wallet_balances;
create policy "Users can read their own wallet" on public.wallet_balances
  for select to authenticated using (auth.uid() = user_id);

create table if not exists public.wallet_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  tx_ref text not null unique,
  flutterwave_transaction_id text not null unique,
  amount_ngn integer not null check (amount_ngn > 0),
  credits integer not null check (credits > 0),
  created_at timestamptz not null default now()
);
alter table public.wallet_transactions enable row level security;
grant select on public.wallet_transactions to authenticated;
drop policy if exists "Users can read their own wallet transactions" on public.wallet_transactions;
create policy "Users can read their own wallet transactions" on public.wallet_transactions
  for select to authenticated using (auth.uid() = user_id);

create or replace function public.credit_multivexa_wallet(
  p_user_id uuid,
  p_tx_ref text,
  p_transaction_id text,
  p_amount_ngn integer,
  p_credits integer
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted_count integer;
  current_credits integer;
begin
  if p_amount_ngn <= 0 or p_credits <= 0 or p_tx_ref = '' or p_transaction_id = '' then
    raise exception 'Invalid wallet transaction';
  end if;

  insert into public.wallet_transactions(user_id, tx_ref, flutterwave_transaction_id, amount_ngn, credits)
  values (p_user_id, p_tx_ref, p_transaction_id, p_amount_ngn, p_credits)
  on conflict do nothing;
  get diagnostics inserted_count = row_count;

  if inserted_count = 1 then
    insert into public.wallet_balances(user_id, credits, updated_at)
    values (p_user_id, p_credits, now())
    on conflict (user_id) do update
      set credits = public.wallet_balances.credits + excluded.credits,
          updated_at = now();
  end if;

  select credits into current_credits from public.wallet_balances where user_id = p_user_id;
  return jsonb_build_object('credits', coalesce(current_credits, 0), 'credited', inserted_count = 1);
end;
$$;
revoke all on function public.credit_multivexa_wallet(uuid, text, text, integer, integer) from public, anon, authenticated;
grant execute on function public.credit_multivexa_wallet(uuid, text, text, integer, integer) to service_role;
